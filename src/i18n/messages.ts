function mergeMessageTrees(
  base: MessageTree,
  overrides: MessageTree,
): MessageTree {
  const merged: Record<string, MessageValue> = { ...base };
  for (const [key, override] of Object.entries(overrides)) {
    const baseValue = base[key];
    merged[key] =
      typeof baseValue === "object" &&
      baseValue !== null &&
      typeof override === "object" &&
      override !== null
        ? mergeMessageTrees(baseValue, override)
        : override;
  }
  return merged;
}

export type Messages = MessageTree;

export function messagesForLocale(locale: UiLocale): Messages {
  return mergeMessageTrees(
    translated[locale],
    coverageTranslations[locale] ?? {},
  );
}
